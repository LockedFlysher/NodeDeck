static inline int hud_measure_text(const char *text, int scale) {
    if (!text || !text[0]) return 0;
    int len = (int)strlen(text);
    return (len * 6 - 1) * scale;
}

static inline void hud_draw_text(SDL_Renderer *r, int x, int y, const char *text, int scale, SDL_Color col) {
    if (!text || !text[0]) return;
    SDL_SetRenderDrawColor(r, col.r, col.g, col.b, col.a);
    int cx = x;
    for (const unsigned char *p = (const unsigned char *)text; *p; p++) {
        unsigned char c = *p;
        if (c < 0x20 || c > 0x7E) c = '?';
        const uint8_t *glyph = ND_FONT5X7[c - 0x20];
        for (int gx = 0; gx < 5; gx++) {
            uint8_t colbits = glyph[gx];
            for (int gy = 0; gy < 7; gy++) {
                if (colbits & (1u << gy)) {
                    SDL_Rect px = { cx + gx * scale, y + gy * scale, scale, scale };
                    SDL_RenderFillRect(r, &px);
                }
            }
        }
        cx += 6 * scale;
    }
}

static inline void hud_fill_circle(SDL_Renderer *r, int cx, int cy, int rad, SDL_Color col) {
    SDL_SetRenderDrawColor(r, col.r, col.g, col.b, col.a);
    for (int dy = -rad; dy <= rad; dy++) {
        int dx = (int)sqrt((double)(rad * rad - dy * dy));
        SDL_RenderDrawLine(r, cx - dx, cy + dy, cx + dx, cy + dy);
    }
}

static inline void hud_fill_rounded_rect(SDL_Renderer *r, SDL_Rect rc, int rad, SDL_Color col) {
    if (rad < 0) rad = 0;
    if (rad > rc.w / 2) rad = rc.w / 2;
    if (rad > rc.h / 2) rad = rc.h / 2;
    SDL_SetRenderDrawColor(r, col.r, col.g, col.b, col.a);
    if (rad == 0) {
        SDL_RenderFillRect(r, &rc);
        return;
    }
    SDL_Rect mid = { rc.x, rc.y + rad, rc.w, rc.h - 2 * rad };
    if (mid.h > 0) SDL_RenderFillRect(r, &mid);
    for (int dy = 0; dy < rad; dy++) {
        int cy = rad - 1 - dy;
        int dx = (int)sqrt((double)(rad * rad - cy * cy));
        int inset = rad - dx;
        SDL_RenderDrawLine(r, rc.x + inset, rc.y + dy, rc.x + rc.w - 1 - inset, rc.y + dy);
        SDL_RenderDrawLine(r, rc.x + inset, rc.y + rc.h - 1 - dy, rc.x + rc.w - 1 - inset, rc.y + rc.h - 1 - dy);
    }
}

static inline void hud_draw_rounded_border(SDL_Renderer *r, SDL_Rect rc, int rad, SDL_Color col) {
    if (rad < 0) rad = 0;
    if (rad > rc.w / 2) rad = rc.w / 2;
    if (rad > rc.h / 2) rad = rc.h / 2;
    SDL_SetRenderDrawColor(r, col.r, col.g, col.b, col.a);
    SDL_RenderDrawLine(r, rc.x + rad, rc.y, rc.x + rc.w - 1 - rad, rc.y);
    SDL_RenderDrawLine(r, rc.x + rad, rc.y + rc.h - 1, rc.x + rc.w - 1 - rad, rc.y + rc.h - 1);
    SDL_RenderDrawLine(r, rc.x, rc.y + rad, rc.x, rc.y + rc.h - 1 - rad);
    SDL_RenderDrawLine(r, rc.x + rc.w - 1, rc.y + rad, rc.x + rc.w - 1, rc.y + rc.h - 1 - rad);
    for (int dy = 0; dy < rad; dy++) {
        int cy = rad - 1 - dy;
        int dx = (int)sqrt((double)(rad * rad - cy * cy));
        int inset = rad - dx;
        SDL_RenderDrawPoint(r, rc.x + inset, rc.y + dy);
        SDL_RenderDrawPoint(r, rc.x + rc.w - 1 - inset, rc.y + dy);
        SDL_RenderDrawPoint(r, rc.x + inset, rc.y + rc.h - 1 - dy);
        SDL_RenderDrawPoint(r, rc.x + rc.w - 1 - inset, rc.y + rc.h - 1 - dy);
    }
}

static inline bool hud_pt_in_rect(int px, int py, SDL_Rect rc) {
    return px >= rc.x && px < rc.x + rc.w && py >= rc.y && py < rc.y + rc.h;
}

